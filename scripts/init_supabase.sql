-- RouteOps Live Telemetry Schema & RLS Policies for Supabase
CREATE TABLE IF NOT EXISTS public.routeops_telemetry_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    request_id TEXT NOT NULL,
    query_text TEXT NOT NULL,
    redacted_query TEXT NOT NULL,
    detected_lang TEXT NOT NULL,
    routed_class TEXT NOT NULL,
    routed_tier TEXT NOT NULL,
    confidence NUMERIC(5, 4) NOT NULL,
    latency_ms NUMERIC(8, 2) NOT NULL,
    cost_saved_usd NUMERIC(10, 6) NOT NULL,
    is_cache_hit BOOLEAN DEFAULT false NOT NULL,
    is_guardrail_triggered BOOLEAN DEFAULT false NOT NULL
);

-- Enable Row Level Security (RLS)
ALTER TABLE public.routeops_telemetry_logs ENABLE ROW LEVEL SECURITY;

-- Allow anonymous visitor insert for the public live showcase
CREATE POLICY "Allow public anonymous insert"
ON public.routeops_telemetry_logs
FOR INSERT
TO anon
WITH CHECK (true);

-- Allow public anonymous read for telemetry aggregates
CREATE POLICY "Allow public anonymous select"
ON public.routeops_telemetry_logs
FOR SELECT
TO anon
USING (true);

-- Performance indices
CREATE INDEX IF NOT EXISTS idx_telemetry_created_at ON public.routeops_telemetry_logs(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_telemetry_routed_class ON public.routeops_telemetry_logs(routed_class);
